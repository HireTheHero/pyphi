# Networks with verified non-zero Phi in IIT 4.0, keyed by node count.
# Value: (network_label, loader_sentinel, state)
# Loader sentinels: "basic", "micro", "rule152_N" (rule-152 ring CA of size N)
_VERIFIED_NETWORKS: dict[int, tuple[str, str, tuple[int, ...]]] = {
    3: ("basic_network", "basic", (0, 0, 0)),
    4: ("micro (IIT 4.0 paper)", "micro", (1, 1, 1, 1)),
    5: ("rule152 ring CA (N=5)", "rule152_5", (0, 0, 0, 0, 0)),
    6: ("rule152 ring CA (N=6)", "rule152_6", (0, 0, 0, 0, 0, 0)),
    7: ("rule152 ring CA (N=7)", "rule152_7", (0, 0, 0, 0, 0, 0, 0)),
}


def _make_rule_ca(rule_num: int, n: int):
    """Generate a rule-{rule_num} ring CA network of size N."""
    import numpy as np
    from pyphi import Network

    rule = {((i >> 2) & 1, (i >> 1) & 1, i & 1): (rule_num >> i) & 1 for i in range(8)}
    cm = np.zeros((n, n), dtype=int)
    for i in range(n):
        cm[(i - 1) % n, i] = 1
        cm[i, i] = 1
        cm[(i + 1) % n, i] = 1
    tpm = np.zeros((2**n, n), dtype=float)
    for s in range(2**n):
        state = [(s >> i) & 1 for i in range(n)]
        for i in range(n):
            tpm[s, i] = rule[(state[(i - 1) % n], state[i], state[(i + 1) % n])]
    return Network(tpm, cm=cm)


def _worker(n: int, use_cache: bool, result_queue: multiprocessing.Queue):
    """Run SIA for an N-node network and put elapsed seconds into result_queue."""
    import os
    import time

    import numpy as np

    os.environ.setdefault("PYPHI_WELCOME_OFF", "yes")

    import pyphi
    import pyphi.new_big_phi as nb
    from pyphi import Network, Subsystem

    pyphi.config.WELCOME_OFF = True
    pyphi.config.PROGRESS_BARS = False
    pyphi.config.CACHE_REPERTOIRES = use_cache

    try:
        _, loader, state = _VERIFIED_NETWORKS[n]

        if loader == "basic":
            import pyphi.examples as ex
            network = ex.basic_network()
        elif loader == "micro":
            network = Network(np.array(_MICRO_TPM), cm=np.array(_MICRO_CM))
        elif loader == "rule152_5":
            network = Network(np.array(_RULE152_TPM), cm=np.array(_RULE152_CM))
        elif loader.startswith("rule152_"):
            size = int(loader.split("_")[1])
            network = _make_rule_ca(152, size)
        else:
            raise ValueError(f"Unknown loader: {loader}")

        subsys = Subsystem(network, state, network.node_indices)

        t0 = time.perf_counter()
        result = nb.sia(subsys)
        elapsed = time.perf_counter() - t0

        result_queue.put(("ok", elapsed, float(result.phi)))
    except Exception as exc:
        result_queue.put(("error", 0.0, str(exc)))


def run_with_timeout(n: int, use_cache: bool, timeout: int):
    """Run _worker in a subprocess; return (status, elapsed, phi_or_msg)."""
    ctx = multiprocessing.get_context("spawn")
    q: multiprocessing.Queue = ctx.Queue()
    p = ctx.Process(target=_worker, args=(n, use_cache, q))

    t0 = time.perf_counter()
    p.start()
    p.join(timeout)
    wall = time.perf_counter() - t0

    if p.is_alive():
        p.terminate()
        p.join(5)
        if p.is_alive():
            p.kill()
            p.join()
        return "timeout", wall, None

    if not q.empty():
        status, elapsed, extra = q.get_nowait()
        return status, elapsed, extra

    return "error", wall, "worker exited with no result"


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--max-n", type=int, default=6,
        help="Maximum N to benchmark (default: 6; N=7 is rule152 ring CA, O(hours) sequential)",
    )
    parser.add_argument(
        "--timeout", type=int, default=7200,
        help="Per-N timeout in seconds (default: 7200)",
    )
    parser.add_argument(
        "--no-cache", action="store_true",
        help="Disable repertoire caching",
    )
    args = parser.parse_args()

    use_cache = not args.no_cache
    max_n = args.max_n

    header = f"{'N':>3}  {'Network':<32}  {'Time (s)':>10}  {'Phi':>8}  Status"
    sep = "-" * len(header)
    print(header)
    print(sep)

    rows: list[tuple] = []

    for n in range(3, max_n + 1):
        if n not in _VERIFIED_NETWORKS:
            net_label = "—"
            print(f"{n:>3}  {'(no validated network)':32}  {'—':>10}  {'—':>8}  SKIP")
            rows.append((n, "no validated network", "—", "—", "SKIP"))
            continue

        net_label = _VERIFIED_NETWORKS[n][0]
        sys.stdout.write(f"{n:>3}  {net_label:<32}  {'...':>10}\r")
        sys.stdout.flush()

        status, elapsed, extra = run_with_timeout(n, use_cache, args.timeout)

        if status == "ok":
            phi_str = f"{extra:.6f}"
            time_str = f"{elapsed:.1f}"
            status_str = "OK"
        elif status == "timeout":
            phi_str = "—"
            time_str = f">{args.timeout}"
            status_str = "TIMEOUT"
        else:
            phi_str = "—"
            time_str = f"{elapsed:.1f}"
            status_str = f"ERROR: {extra}"

        print(f"{n:>3}  {net_label:<32}  {time_str:>10}  {phi_str:>8}  {status_str}")
        rows.append((n, net_label, time_str, phi_str, status_str))

        if status == "timeout":
            print(f"\nStopped after N={n} (timeout={args.timeout}s). Skipping larger N.")
            break

    # -----------------------------------------------------------------------
    # Optionally append results to docs/speed_memory.md
    # -----------------------------------------------------------------------
    docs_path = Path(__file__).parent.parent / "docs" / "speed_memory.md"
    if docs_path.exists():
        import datetime
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d")
        cache_label = "on" if use_cache else "off"
        section = [
            "",
            "---",
            "",
            f"## Scaling Benchmark ({timestamp})",
            "",
            "Wall-clock time for `new_big_phi.sia()` (IIT 4.0, sequential) on networks"
            f" with verified non-zero Phi. Timeout per N: {args.timeout}s. Cache: {cache_label}.",
            "",
            "| N | Network | Time (s) | Phi | Status |",
            "|---|---|---|---|---|",
        ]
        for n, net, t, phi, st in rows:
            section.append(f"| {n} | `{net}` | {t} | {phi} | {st} |")
        section.append("")

        with open(docs_path, "a") as f:
            f.write("\n".join(section) + "\n")
        print(f"\nResults appended to {docs_path}")


if __name__ == "__main__":
    main()

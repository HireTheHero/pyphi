"""Scaling benchmark: wall-clock time for full SIA as a function of N nodes.

Motivation: upstream issue #117 reports ~2 hours for a 6-node system on IIT 3.0.
This script characterises how computation time scales with N on the current fork
(IIT 4.0) so we have a baseline for the develop branch.

Usage:
    uv run python script/bench_scaling.py
    uv run python script/bench_scaling.py --max-n 6 --timeout 3600
    uv run python script/bench_scaling.py --max-n 7 --timeout 7200

Options:
    --max-n INT       Maximum number of nodes to test (default: 6)
    --timeout INT     Per-N wall-clock timeout in seconds (default: 7200)
    --no-cache        Disable repertoire caching (default: cache on)

Network selection:
    Networks are chosen to have VERIFIED NON-ZERO Phi in IIT 4.0, so the
    partition search actually runs rather than short-circuiting via
    SHORTCIRCUIT_SIA.

    N=3  pyphi.examples.basic_network(), state (0,0,0)            phi≈2.0
    N=4  Micro network (Albantakis et al. IIT 4.0 paper),         phi≈1.33
         state all-ones; tested in test_big_phi.py::test_sia_micro_*
    N=5  Rule-152 5-node ring CA, state all-zeros                  phi≈0.83
         tested in test_big_phi.py::test_sia_rule152_s_*
    N=6  Rule-152 6-node ring CA, state all-zeros                  phi≈0.28
         generated by make_rule_ca(152, 6); ~8 min on Apple M-series
    N=7  Rule-152 7-node ring CA, state all-zeros                  phi≈TBD
         generated by make_rule_ca(152, 7); expected O(hours) sequential
    N=8+ No network defined; row is marked SKIP.

Each N is run in a subprocess with a hard wall-clock timeout so the script
terminates cleanly even if computation would otherwise take days.
Results are printed as a table and appended to docs/speed_memory.md if that
file is found relative to this script's parent directory.
"""

